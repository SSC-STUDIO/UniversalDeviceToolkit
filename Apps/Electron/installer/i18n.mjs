export function installerLocale(language) {
  const tag = String(language ?? '').replaceAll('_', '-').toLowerCase()
  if (/^zh-(hant|tw|hk|mo)(-|$)/.test(tag)) return 'zh-Hant'
  return /^zh(-|$)/.test(tag) ? 'zh-CN' : 'en-US'
}

export function installerText(language, key, parameters = {}) {
  const locale = installerLocale(language)
  const value = catalogs[locale][key] ?? catalogs['en-US'][key] ?? key
  return value.replace(/\{(\w+)\}/g, (placeholder, name) => String(parameters[name] ?? placeholder))
}

const progressLabels = {
  preparing: 'phasePreparing', downloading: 'phaseDownloading',
  extracting: 'phaseExtracting', copying: 'copying', complete: 'phaseComplete'
}

export function installerProgressText(language, progress) {
  if (progress.phase === 'warning') return String(progress.message ?? '')
  return installerText(language, progressLabels[progress.phase] ?? 'installingTitle')
}
